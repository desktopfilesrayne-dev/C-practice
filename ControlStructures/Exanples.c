//Controll Stuctures Examples
#include <stdio.h>
int main() {
    int x=5;
    switch(x) {
        case 1:
            printf("x is 1\n");
            break;
        case 2:
            printf("x is 2\n");
            break;
        case 3:
            printf("x is 3\n");
            break;
        case 4:
            printf("x is 4\n");
            break;
        case 5:
            printf("x is 5\n");
            break;
        default:
            printf("x is not between 1 and 5\n");
    }
}